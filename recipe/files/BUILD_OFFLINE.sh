#!/usr/bin/env bash
# =============================================================================
# ReadyStack — offline reproducible rebuild.
#
# Rebuilds this product's image from THIS ARCHIVE ALONE, with no network access
# of any kind, and prints the resulting linux/amd64 image-manifest digest.
# Run ./VERIFY_OFFLINE.sh afterwards to assert it equals the published digest.
#
# Requirements: linux/amd64 Docker host, docker buildx >= 0.30, jq, tar.
# No git, no registry access, no additional tooling.
#
#   ./BUILD_OFFLINE.sh                the rebuild (OCI image + a docker-loadable copy)
#   ./BUILD_OFFLINE.sh --provenance   the same rebuild with SLSA v1 build provenance (mode=max) attached to the OCI
#                                     image, generated by BuildKit, not by any build step. Your build platform runs
#                                     the build and signs that provenance with a key the build steps cannot reach
#                                     (see REBUILD.md). Any SLSA build level is your platform's; this archive claims
#                                     none. The image digest is the same either way.
#   ./BUILD_OFFLINE.sh --restore-modes   only put back file modes your unpacking changed (see below), then exit
#
# File modes are build input: COPY carries them into the image. `tar -xzf` without -p, as a non-root user, applies
# your umask to every file (664 becomes 644 under umask 022). FILE_MODES.tsv records every file's and directory's
# mode as packed, and every run of this script first puts back any that differ.
# =============================================================================
set -euo pipefail
PROVENANCE=0
MODES_ONLY=0
for arg in "$@"; do
  case "$arg" in
    --provenance) PROVENANCE=1 ;;
    --restore-modes) MODES_ONLY=1 ;;
    -h|--help) sed -n '2,/^# ====/{/^# ====/!p}' "$0"; exit 0 ;;
    *) echo "ERROR: unknown option $arg (use --provenance, --restore-modes or nothing)" >&2; exit 2 ;;
  esac
done
cd "$(dirname "$(readlink -f "$0")")"
KIT="$PWD"

fail(){ echo "ERROR: $*" >&2; exit 1; }

# --- 0. file modes as packed (FILE_MODES.tsv) ---------------------------------
# One line per file or directory: `<octal mode><TAB><path>` (no path in it holds a tab or a newline). Only modes that
# differ are changed, grouped by mode, so a tree unpacked with -p costs one listing. GNU find prints modes itself; BSD
# find (macOS) has no -printf, so stat does.
restore_modes(){
  [ -f FILE_MODES.tsv ] || return 0
  local now diff n m
  if find . -maxdepth 0 -printf '' >/dev/null 2>&1; then
    now=$(find . -mindepth 1 \( -type f -o -type d \) -printf '%m\t%P\n')
  else
    now=$(find . -mindepth 1 \( -type f -o -type d \) -exec stat -f '%Lp%t%N' {} + | sed 's|	\./|	|')
  fi
  diff=$(printf '%s\n' "$now" | awk -F'\t' '
    NR == FNR { if ($1 ~ /^[0-7]+$/ && index($0, "\t")) want[substr($0, index($0, "\t") + 1)] = $1; next }
    { p = substr($0, index($0, "\t") + 1); if ((p in want) && want[p] != $1) print want[p] "\t" p }' FILE_MODES.tsv -)
  [ -n "$diff" ] || return 0
  n=$(printf '%s\n' "$diff" | awk 'END { print NR }')
  echo "==> putting back the packed mode of $n file(s) and directories (this archive was unpacked without tar -p)"
  for m in $(printf '%s\n' "$diff" | cut -f1 | sort -u); do
    printf '%s\n' "$diff" | awk -F'\t' -v m="$m" '$1 == m { print substr($0, index($0, "\t") + 1) }' | tr '\n' '\0' \
      | xargs -0 chmod "$m" -- \
      || fail "could not restore file modes from FILE_MODES.tsv; unpack the archive again with: tar -xpzf <archive>"
  done
}
restore_modes
if [ "$MODES_ONLY" = 1 ]; then
  echo "==> file modes match FILE_MODES.tsv"
  exit 0
fi

# --- host guards ------------------------------------------------------------
command -v docker >/dev/null || fail "docker not found"
command -v jq     >/dev/null || fail "jq not found"
ARCH=$(docker version -f '{{.Server.Arch}}' 2>/dev/null) || fail "cannot reach the Docker daemon"
[ "$ARCH" = "amd64" ] || fail "this image is linux/amd64; your Docker daemon reports '$ARCH'.
       Reproduction is defined for linux/amd64 only — this is a scope limit, not a mismatch."
docker buildx version >/dev/null 2>&1 || fail "docker buildx not available"

[ -f SOURCE_DATE_EPOCH.txt ] || fail "SOURCE_DATE_EPOCH.txt missing — not a reproducible archive"
SDE=$(tr -dc '0-9' < SOURCE_DATE_EPOCH.txt)
[ -n "$SDE" ] && [ "$SDE" -gt 0 ] || fail "SOURCE_DATE_EPOCH must be a positive integer"

DOCKERFILE=$(cat DOCKERFILE_NAME.txt 2>/dev/null || echo Dockerfile.offline.pinned)
[ -f "$DOCKERFILE" ] || fail "$DOCKERFILE missing"

# --- 1. pinned builder toolchain, loaded from the archive (never pulled) -----
# Always load the archive's copy (a host image under the same public tag may differ), then build from a name no
# registry can serve: buildx's docker-container driver tries to PULL its image before using a local one, so with the
# public tag a networked host would contact Docker Hub (and take a re-pointed tag). `.invalid` never resolves.
BK_TAG=$(cat toolchain/BUILDKIT_TAG.txt)
echo "==> loading pinned BuildKit toolchain from the archive ($BK_TAG)"
docker load -i toolchain/buildkit.tar >/dev/null
BK_LOCAL="readystack.invalid/buildkit:pinned"
docker tag "$BK_TAG" "$BK_LOCAL"
BUILDER="readystack-repro-$$"
echo "==> creating hermetic builder $BUILDER from the vendored toolchain"
docker buildx create --name "$BUILDER" --driver docker-container \
  --driver-opt "image=$BK_LOCAL" --bootstrap >/dev/null
cleanup(){ docker buildx rm "$BUILDER" >/dev/null 2>&1 || true; }
trap cleanup EXIT

# --- 2. remap every FROM to a vendored, digest-preserving OCI layout ---------
# This is what makes the build genuinely offline: `--network=none` only isolates
# RUN steps, so without these remaps BuildKit would still resolve each base from
# a registry.
CTX=()
while IFS=$'\t' read -r ref path; do
  [ -z "${ref:-}" ] && continue
  [ -d "$path" ] || fail "vendored base layout missing: $path"
  d=$(jq -r '.manifests[0].digest' "$path/index.json")
  CTX+=(--build-context "$ref=oci-layout://$KIT/$path@$d")
  echo "==> base pinned offline: $ref  <-  $path@${d:0:19}…"
done < BASES.tsv

# --- 3. the build ------------------------------------------------------------
rm -f rebuilt.oci.tar rebuilt.docker.tar
if [ "$PROVENANCE" = 1 ]; then
  echo "==> building (--network=none, SOURCE_DATE_EPOCH=$SDE, SLSA v1 provenance attached)"
  docker buildx build --builder "$BUILDER" --no-cache --network=none \
    --attest type=provenance,mode=max,version=v1 --sbom=false --platform=linux/amd64 \
    --build-arg "SOURCE_DATE_EPOCH=$SDE" "${CTX[@]}" \
    -f "$DOCKERFILE" \
    -o "type=oci,dest=$KIT/rebuilt.oci.tar,rewrite-timestamp=true" \
    .
  # Docker's docker-format exporter cannot carry attestations, so the docker-loadable copy is the same build again
  # on the same builder, served from its cache.
  echo "==> exporting the docker-loadable copy of the same image (from the build cache)"
  docker buildx build --builder "$BUILDER" --network=none \
    --provenance=false --sbom=false --platform=linux/amd64 \
    --build-arg "SOURCE_DATE_EPOCH=$SDE" "${CTX[@]}" \
    -f "$DOCKERFILE" \
    -o "type=docker,dest=$KIT/rebuilt.docker.tar,rewrite-timestamp=true" \
    .
else
  echo "==> building (--network=none, SOURCE_DATE_EPOCH=$SDE)"
  docker buildx build --builder "$BUILDER" --no-cache --network=none \
    --provenance=false --sbom=false --platform=linux/amd64 \
    --build-arg "SOURCE_DATE_EPOCH=$SDE" "${CTX[@]}" \
    -f "$DOCKERFILE" \
    -o "type=oci,dest=$KIT/rebuilt.oci.tar,rewrite-timestamp=true" \
    -o "type=docker,dest=$KIT/rebuilt.docker.tar,rewrite-timestamp=true" \
    .
fi

# The OCI export carries the digest we claim; the docker export is the same
# build, emitted in the one format `docker load` accepts (it cannot read an
# OCI layout). The digest is always the linux/amd64 IMAGE manifest: with
# provenance attached, index.json points at an index holding that manifest and
# its attestation manifest, so read the image manifest out of it.
blob(){ tar -xOf rebuilt.oci.tar "blobs/sha256/$1" 2>/dev/null || tar -xOf rebuilt.oci.tar "./blobs/sha256/$1"; }
TOP=$(tar -xOf rebuilt.oci.tar index.json | jq -r '.manifests[0].digest')
TOPMT=$(tar -xOf rebuilt.oci.tar index.json | jq -r '.manifests[0].mediaType')
if [ "$TOPMT" = "application/vnd.oci.image.index.v1+json" ]; then
  X=$(blob "${TOP#sha256:}" | jq -r '[.manifests[] | select(.platform.os=="linux" and .platform.architecture=="amd64")][0].digest')
else
  X=$TOP
fi
[ -n "$X" ] && [ "$X" != null ] || fail "could not read the rebuilt image-manifest digest"
echo "$X" > REBUILT_DIGEST.txt
echo
echo "REBUILT_DIGEST=$X"
[ "$PROVENANCE" = 1 ] && echo "SLSA v1 provenance: attached to the image in rebuilt.oci.tar (generated by BuildKit); sign it on your build platform."
echo "Next: ./VERIFY_OFFLINE.sh"
